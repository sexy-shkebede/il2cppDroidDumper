package dev.il2cpp.dumper.core.extra

import dev.il2cpp.dumper.core.outputs.StructGenerator

/**
 * Code generators for modders: C++ offsets header, Frida (raw + frida-il2cpp-bridge) hooks,
 * C++ hook templates (Dobby / ShadowHook / And64InlineHook) and field structs.
 */
object CodeGen {
    private fun hex(v: Long) = "0x" + java.lang.Long.toHexString(v).uppercase()

    fun ident(s: String): String = StructGenerator.fixName(s)

    private fun stripGenerics(name: String): String {
        val i = name.indexOf('<')
        return if (i > 0) name.substring(0, i) else name
    }

    fun moduleName(info: DumpInfo): String = when {
        info.format.startsWith("PE") -> "GameAssembly.dll"
        info.format.startsWith("Mach") -> "UnityFramework"
        info.format == "NSO" -> "main"
        else -> "libil2cpp.so"
    }

    /** C type used for a C# type name in hook templates. */
    fun cType(csType: String): String {
        val t = csType.removePrefix("ref ").trim()
        return when (t) {
            "void" -> "void"
            "bool" -> "bool"
            "byte" -> "uint8_t"
            "sbyte" -> "int8_t"
            "short" -> "int16_t"
            "ushort" -> "uint16_t"
            "char" -> "uint16_t"
            "int" -> "int32_t"
            "uint" -> "uint32_t"
            "long" -> "int64_t"
            "ulong" -> "uint64_t"
            "float" -> "float"
            "double" -> "double"
            "IntPtr" -> "intptr_t"
            "UIntPtr" -> "uintptr_t"
            "string" -> "Il2CppString*"
            "Vector2" -> "Vector2"
            "Vector3" -> "Vector3"
            "Quaternion" -> "Quaternion"
            "Color" -> "Color"
            else -> if (t.endsWith("*")) "void*" else "void*"
        }
    }

    private fun isFloatType(csType: String) = csType == "float" || csType == "double"

    // ------------------------------------------------------------------ offsets.h
    fun offsetsHeader(index: DumpIndex, types: List<TypeEntry>, includeFields: Boolean = true): String {
        val sb = StringBuilder()
        val info = index.info
        sb.append("// Generated by Il2Cpp Dumper for Android\n")
        if (info.title.isNotEmpty()) sb.append("// Game: ${info.title}${if (info.packageName.isNotEmpty()) " (${info.packageName})" else ""}\n")
        sb.append("// Unity: ${info.unityVersion.ifEmpty { "?" }} | metadata v${info.metadataVersion} | il2cpp v${info.il2cppVersion} | ${info.arch}\n")
        sb.append("// Offsets are RVAs relative to ${moduleName(info)}\n")
        sb.append("#pragma once\n#include <cstdint>\n\nnamespace Offsets {\n")
        val usedTypeNames = HashMap<String, Int>()
        for (type in types) {
            val methods = type.methods.filter { it.hasBody }
            val fields = if (includeFields) type.fields.filter { !it.isConst && it.offset >= 0 } else emptyList()
            if (methods.isEmpty() && fields.isEmpty()) continue
            var ns = ident(type.fullName)
            val n = usedTypeNames.merge(ns, 1, Int::plus)!!
            if (n > 1) ns += "_$n"
            sb.append("    // ${type.kind.name.lowercase()} ${type.fullName}")
            if (type.extends.isNotEmpty()) sb.append(" : ${type.extends}")
            sb.append("\n    namespace $ns {\n")
            val used = HashMap<String, Int>()
            for (m in methods) {
                var name = ident(stripGenerics(m.name))
                val c = used.merge(name, 1, Int::plus)!!
                if (c > 1) name += "_$c"
                sb.append("        constexpr uintptr_t $name = ${hex(m.rva)}; // ${m.signature()}\n")
            }
            if (fields.isNotEmpty()) {
                sb.append("        namespace Fields {\n")
                val usedF = HashMap<String, Int>()
                for (f in fields) {
                    var name = ident(f.name)
                    val c = usedF.merge(name, 1, Int::plus)!!
                    if (c > 1) name += "_$c"
                    sb.append("            constexpr uintptr_t $name = ${hex(f.offset.toLong())}; // ${f.modifiers}${f.typeName}\n")
                }
                sb.append("        }\n")
            }
            sb.append("    }\n")
        }
        sb.append("}\n")
        return sb.toString()
    }

    // ------------------------------------------------------------------ Frida (raw)
    fun fridaHook(index: DumpIndex, type: TypeEntry, method: MethodEntry): String {
        val module = moduleName(index.info)
        val sb = StringBuilder()
        val title = "${type.fullName}::${method.name}"
        sb.append("// Frida hook generated by Il2Cpp Dumper for Android\n")
        sb.append("// ${method.signature()}\n")
        sb.append("// RVA ${hex(method.rva)} in $module (il2cpp v${index.info.il2cppVersion}, ${index.info.arch})\n")
        sb.append("// Usage: frida -U -f ${index.info.packageName.ifEmpty { "<package>" }} -l hook.js\n\n")
        sb.append("const MODULE = \"$module\";\n")
        sb.append("const RVA = ptr(\"${hex(method.rva)}\");\n\n")
        sb.append("function install() {\n")
        sb.append("    const mod = Process.findModuleByName(MODULE);\n")
        sb.append("    if (mod === null) { setTimeout(install, 300); return; }\n")
        sb.append("    const target = mod.base.add(RVA);\n")
        sb.append("    console.log(\"[*] Hooking $title @ \" + target);\n")
        sb.append("    Interceptor.attach(target, {\n")
        sb.append("        onEnter(args) {\n")
        var argIndex = 0
        val argLines = ArrayList<String>()
        if (!method.isStatic) {
            sb.append("            this.self = args[0]; // ${type.name} instance\n")
            argLines.add("this=\" + args[0] + \"")
            argIndex++
        }
        var floatNote = false
        for (p in method.params) {
            if (isFloatType(p.typeName) && p.prefix.isEmpty()) {
                sb.append("            // ${p.typeName} ${p.name} is passed in a floating point register (not in args[])\n")
                floatNote = true
                continue
            }
            val reader = when (p.typeName) {
                "string" -> "readIl2CppString(args[$argIndex])"
                "bool" -> "(args[$argIndex].toInt32() & 1) === 1"
                "int", "short", "sbyte" -> "args[$argIndex].toInt32()"
                "uint", "ushort", "byte" -> "args[$argIndex].toUInt32()"
                else -> "args[$argIndex]"
            }
            sb.append("            const ${jsIdent(p.name)} = $reader; // ${p}\n")
            argLines.add("${p.name}=\" + ${jsIdent(p.name)} + \"")
            argIndex++
        }
        sb.append("            console.log(\"[+] $title(" + argLines.joinToString(", ") + ")\");\n")
        sb.append("        },\n")
        sb.append("        onLeave(retval) {\n")
        when (method.returnType) {
            "void" -> sb.append("            // void method\n")
            "bool" -> sb.append("            console.log(\"    -> \" + ((retval.toInt32() & 1) === 1));\n            // retval.replace(ptr(1)); // force true\n")
            "int", "uint", "short", "ushort", "byte", "sbyte" -> sb.append("            console.log(\"    -> \" + retval.toInt32());\n            // retval.replace(ptr(9999));\n")
            "float", "double" -> sb.append("            // ${method.returnType} return value is in a floating point register (s0/d0)\n")
            "string" -> sb.append("            console.log(\"    -> \" + readIl2CppString(retval));\n")
            else -> sb.append("            console.log(\"    -> \" + retval);\n")
        }
        sb.append("        }\n")
        sb.append("    });\n")
        sb.append("}\n\n")
        sb.append(FRIDA_STRING_HELPER.replace("%PTR%", if (index.info.is32Bit) "8" else "16").replace("%LEN%", if (index.info.is32Bit) "8" else "16"))
        sb.append("\ninstall();\n")
        if (floatNote) sb.append("// Tip: use frida-il2cpp-bridge for full access to float arguments.\n")
        return sb.toString()
    }

    private fun jsIdent(name: String): String {
        val s = ident(name)
        return if (s in JS_RESERVED) "${s}_" else s
    }

    private val JS_RESERVED = setOf("this", "function", "var", "let", "const", "new", "delete", "in", "of", "class", "return", "default", "switch", "case", "with", "yield", "await", "enum", "export", "import", "super", "typeof", "void", "instanceof")

    private const val FRIDA_STRING_HELPER = """function readIl2CppString(str) {
    if (str.isNull()) return null;
    // System.String: klass, monitor, int32 length, char16 chars[]
    const length = str.add(%LEN%).readS32();
    return str.add(%LEN% + 4).readUtf16String(length);
}
"""

    // ------------------------------------------------------------------ frida-il2cpp-bridge
    fun fridaBridgeHook(index: DumpIndex, type: TypeEntry, method: MethodEntry): String {
        val image = index.images.getOrNull(type.imageIndex)?.removeSuffix(".dll") ?: "Assembly-CSharp"
        val className = type.fullName.replace('.', '.').let { stripGenerics(it) }
        val paramCount = method.params.size
        val sb = StringBuilder()
        sb.append("// frida-il2cpp-bridge hook generated by Il2Cpp Dumper for Android\n")
        sb.append("// npm i frida-il2cpp-bridge ; frida -U -f ${index.info.packageName.ifEmpty { "<package>" }} -l agent.js\n")
        sb.append("import \"frida-il2cpp-bridge\";\n\n")
        sb.append("Il2Cpp.perform(() => {\n")
        sb.append("    const klass = Il2Cpp.domain.assembly(\"$image\").image.class(\"$className\");\n")
        sb.append("    const method = klass.method(\"${stripGenerics(method.name)}\", $paramCount);\n")
        sb.append("    // ${method.signature()}\n")
        sb.append("    method.implementation = function (")
        sb.append(method.params.joinToString(", ") { jsIdent(it.name) })
        sb.append(") {\n")
        sb.append("        console.log(\"[+] ${type.name}.${method.name} called\"")
        for (p in method.params) sb.append(", \"${p.name}=\", ${jsIdent(p.name)}")
        sb.append(");\n")
        val call = if (method.isStatic) "klass.method(\"${stripGenerics(method.name)}\", $paramCount)" else "this.method(\"${stripGenerics(method.name)}\", $paramCount)"
        if (method.returnType == "void") {
            sb.append("        $call.invoke(${method.params.joinToString(", ") { jsIdent(it.name) }});\n")
        } else {
            sb.append("        const result = $call.invoke(${method.params.joinToString(", ") { jsIdent(it.name) }});\n")
            sb.append("        console.log(\"    -> \", result);\n")
            sb.append("        return result;\n")
        }
        sb.append("    };\n")
        sb.append("});\n")
        return sb.toString()
    }

    // ------------------------------------------------------------------ C++ hook template
    fun cppHook(index: DumpIndex, type: TypeEntry, method: MethodEntry): String {
        val name = ident(type.name.substringAfterLast('.').let(::stripGenerics) + "_" + stripGenerics(method.name))
        val ret = cType(method.returnType)
        val params = ArrayList<String>()
        if (!method.isStatic) params.add("void* __this")
        for (p in method.params) {
            val ct = if (p.prefix.isNotBlank()) cType(p.typeName) + "*" else cType(p.typeName)
            params.add("$ct ${ident(p.name)}")
        }
        params.add("const void* method")
        val args = (if (!method.isStatic) listOf("__this") else emptyList()) + method.params.map { ident(it.name) } + listOf("method")
        val module = moduleName(index.info)
        return buildString {
            append("// C++ hook template generated by Il2Cpp Dumper for Android\n")
            append("// ${type.fullName}: ${method.signature()}\n")
            append("// RVA ${hex(method.rva)} ($module, ${index.info.arch})\n\n")
            append("$ret (*orig_$name)(${params.joinToString(", ")});\n\n")
            append("$ret hook_$name(${params.joinToString(", ")}) {\n")
            append("    // your code here\n")
            if (ret == "void") append("    orig_$name(${args.joinToString(", ")});\n")
            else append("    return orig_$name(${args.joinToString(", ")});\n")
            append("}\n\n")
            append("// Install (after $module is loaded):\n")
            append("// uintptr_t base = findLibrary(\"$module\");\n")
            append("// DobbyHook((void*)(base + ${hex(method.rva)}), (void*)hook_$name, (void**)&orig_$name);\n")
            append("// shadowhook_hook_func_addr((void*)(base + ${hex(method.rva)}), (void*)hook_$name, (void**)&orig_$name);\n")
            append("// A64HookFunction((void*)(base + ${hex(method.rva)}), (void*)hook_$name, (void**)&orig_$name);\n")
        }
    }

    /** Field layout for a type: C struct with offsets as comments + constexpr list. */
    fun fieldLayout(index: DumpIndex, type: TypeEntry): String {
        val sb = StringBuilder()
        sb.append("// ${type.kind.name.lowercase()} ${type.fullName}")
        if (type.extends.isNotEmpty()) sb.append(" : ${type.extends}")
        sb.append("\n")
        val instance = type.fields.filter { !it.isStatic && !it.isConst }
        val statics = type.fields.filter { it.isStatic && !it.isConst }
        val consts = type.fields.filter { it.isConst }
        sb.append("namespace ${ident(type.fullName)}_Offsets {\n")
        for (f in instance) sb.append("    constexpr uintptr_t ${ident(f.name)} = ${hex(f.offset.toLong())}; // ${f.typeName}\n")
        if (statics.isNotEmpty()) {
            sb.append("    // static fields (relative to klass->static_fields)\n")
            for (f in statics) sb.append("    constexpr uintptr_t static_${ident(f.name)} = ${hex(f.offset.toLong())}; // ${f.typeName}\n")
        }
        sb.append("}\n")
        if (consts.isNotEmpty()) {
            sb.append("// constants\n")
            for (f in consts) sb.append("// ${f.typeName} ${f.name} = ${f.defaultValue ?: "?"}\n")
        }
        if (instance.isNotEmpty()) {
            sb.append("\n// Read example: *(${cType(instance.first().typeName)}*)((uintptr_t)instance + ${hex(instance.first().offset.toLong())})\n")
        }
        return sb.toString()
    }

    /** Text block like dump.cs for a single type (for sharing / copying). */
    fun typeAsCSharp(type: TypeEntry): String {
        val sb = StringBuilder()
        sb.append("// Namespace: ${type.namespace}\n")
        sb.append(type.attributes)
        sb.append(type.modifiers)
        sb.append(
            when (type.kind) {
                TypeKind.CLASS -> "class "
                TypeKind.STRUCT -> "struct "
                TypeKind.ENUM -> "enum "
                TypeKind.INTERFACE -> "interface "
            }
        )
        sb.append(type.name)
        if (type.extends.isNotEmpty()) sb.append(" : ").append(type.extends)
        sb.append(" // TypeDefIndex: ${type.typeDefIndex}\n{\n")
        if (type.fields.isNotEmpty()) {
            sb.append("\t// Fields\n")
            for (f in type.fields) {
                sb.append("\t${f.modifiers}${f.typeName} ${f.name}")
                if (f.defaultValue != null) {
                    if (f.defaultValue.startsWith("/*")) sb.append(" ").append(f.defaultValue) else sb.append(" = ").append(f.defaultValue)
                }
                if (!f.isConst) sb.append("; // ${hex(f.offset.toLong() and 0xFFFFFFFFL)}\n") else sb.append(";\n")
            }
        }
        if (type.properties.isNotEmpty()) {
            sb.append("\n\t// Properties\n")
            for (p in type.properties) {
                sb.append("\t${p.modifiers}${p.typeName} ${p.name} { ")
                if (p.hasGet) sb.append("get; ")
                if (p.hasSet) sb.append("set; ")
                sb.append("}\n")
            }
        }
        if (type.methods.isNotEmpty()) {
            sb.append("\n\t// Methods\n")
            for (m in type.methods) {
                sb.append("\n")
                if (m.hasBody) sb.append("\t// RVA: ${hex(m.rva)} Offset: ${hex(m.offset)} VA: ${hex(m.va)}") else sb.append("\t// RVA: -1 Offset: -1")
                if (m.slot >= 0) sb.append(" Slot: ${m.slot}")
                sb.append("\n\t${m.signature()}${if (m.isAbstract) ";" else " { }"}\n")
            }
        }
        sb.append("}\n")
        return sb.toString()
    }
}
